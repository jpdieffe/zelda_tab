// Uses the installed Android SDK/JDK; no Gradle downloads or global changes.
import {execFileSync} from 'node:child_process';
import {mkdirSync,existsSync,copyFileSync,readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {randomBytes} from 'node:crypto';
const root=fileURLToPath(new URL('../',import.meta.url));
const sdk=process.env.ANDROID_HOME||path.join(process.env.LOCALAPPDATA,'Android/Sdk');
const jdk=process.env.FAIRY_JAVA_HOME||'C:/Program Files/Android/Android Studio/jbr';
const bt=path.join(sdk,'build-tools/35.0.0'),platform=path.join(sdk,'platforms/android-35/android.jar');
const build=path.join(root,'android/build'),keys=path.resolve(root,'../.tools/fairy-android-signing');
for(const folder of [build,keys,path.join(build,'classes'),path.join(build,'res/drawable'),path.join(root,'dist/downloads')])mkdirSync(folder,{recursive:true});
const run=(exe,args,options={})=>execFileSync(exe,args,{cwd:root,stdio:'inherit',...options});
const java=path.join(jdk,'bin/java.exe');
const debug=process.argv.includes('--debug');
const manifest=path.join(build,'AndroidManifest.xml');
let manifestText=readFileSync(path.join(root,'android/AndroidManifest.xml'),'utf8');
if(debug)manifestText=manifestText.replace('<application ','<application android:debuggable="true" ');
writeFileSync(manifest,manifestText);
const secretFile=path.join(keys,'signing.json'),keyFile=path.join(keys,'fairy-link.jks');
if(!existsSync(secretFile))writeFileSync(secretFile,JSON.stringify({password:randomBytes(32).toString('hex')}));
const secret=JSON.parse(readFileSync(secretFile,'utf8')).password;
const env={...process.env,FAIRY_SIGN_PASSWORD:secret};
if(!existsSync(keyFile))run(path.join(jdk,'bin/keytool.exe'),['-genkeypair','-keystore',keyFile,'-alias','fairy-link','-keyalg','RSA','-keysize','3072','-validity','10000','-dname','CN=Fairy Link Family App','-storepass:env','FAIRY_SIGN_PASSWORD','-keypass:env','FAIRY_SIGN_PASSWORD'],{env});
copyFileSync(path.join(root,'dist/assets/icon-192.png'),path.join(build,'res/drawable/icon.png'));
run(path.join(bt,'aapt2.exe'),['compile','--dir',path.join(build,'res'),'-o',path.join(build,'resources.zip')]);
run(path.join(bt,'aapt2.exe'),['link','-I',platform,'--manifest',manifest,'-o',path.join(build,'unsigned.apk'),path.join(build,'resources.zip')]);
run(path.join(jdk,'bin/javac.exe'),['-source','8','-target','8','-classpath',platform,'-d',path.join(build,'classes'),path.join(root,'android/src/com/jpdieffe/fairylink/MainActivity.java')]);
run(path.join(jdk,'bin/jar.exe'),['cf',path.join(build,'classes.jar'),'-C',path.join(build,'classes'),'.']);
run(java,['-cp',path.join(bt,'lib/d8.jar'),'com.android.tools.r8.D8','--lib',platform,'--min-api','26','--output',build,path.join(build,'classes.jar')]);
run(path.join(jdk,'bin/jar.exe'),['uf',path.join(build,'unsigned.apk'),'-C',build,'classes.dex']);
run(path.join(bt,'zipalign.exe'),['-f','4',path.join(build,'unsigned.apk'),path.join(build,'aligned.apk')]);
const apk=debug?path.join(build,'fairy-link-test.apk'):path.join(root,'dist/downloads/fairy-link-tablet.apk');
run(java,['-jar',path.join(bt,'lib/apksigner.jar'),'sign','--ks',keyFile,'--ks-key-alias','fairy-link','--ks-pass','env:FAIRY_SIGN_PASSWORD','--key-pass','env:FAIRY_SIGN_PASSWORD','--out',apk,path.join(build,'aligned.apk')],{env});
run(java,['-jar',path.join(bt,'lib/apksigner.jar'),'verify','--verbose',apk]);
console.log('Signed tablet APK:',apk);
